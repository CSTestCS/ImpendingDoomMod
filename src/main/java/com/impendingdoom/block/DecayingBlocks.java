package com.impendingdoom.block;

import com.impendingdoom.registry.ModBlocks;
import net.minecraft.core.registries.Registries;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.level.block.Block;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockBehaviour;
import net.minecraft.world.level.block.state.BlockState;
import net.neoforged.neoforge.registries.DeferredHolder;

import java.util.ArrayList;
import java.util.IdentityHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Supplier;

/**
 * Decaying versions of naturally generated blocks. Models, loot tables and tool tags are generated by
 * {@code tools/gen_decaying.py}, which keeps the same list.
 */
public final class DecayingBlocks {
    public enum Tint { NONE, GRASS, FOLIAGE, BIRCH, SPRUCE }

    public record Entry(String name, Supplier<Block> original, Tint tint, DeferredHolder<Block, Block> holder) {}

    public static final List<Entry> ALL = new ArrayList<>();
    private static Map<Block, Block> byOriginal;

    private DecayingBlocks() {}

    public static void registerAll() {
        add("dirt", () -> Blocks.DIRT, Tint.NONE);
        add("grass_block", () -> Blocks.GRASS_BLOCK, Tint.GRASS);
        add("coarse_dirt", () -> Blocks.COARSE_DIRT, Tint.NONE);
        add("podzol", () -> Blocks.PODZOL, Tint.NONE);
        add("mycelium", () -> Blocks.MYCELIUM, Tint.NONE);
        add("rooted_dirt", () -> Blocks.ROOTED_DIRT, Tint.NONE);
        add("mud", () -> Blocks.MUD, Tint.NONE);
        add("clay", () -> Blocks.CLAY, Tint.NONE);
        add("sand", () -> Blocks.SAND, Tint.NONE);
        add("red_sand", () -> Blocks.RED_SAND, Tint.NONE);
        add("gravel", () -> Blocks.GRAVEL, Tint.NONE);
        add("snow_block", () -> Blocks.SNOW_BLOCK, Tint.NONE);
        add("moss_block", () -> Blocks.MOSS_BLOCK, Tint.NONE);
        add("stone", () -> Blocks.STONE, Tint.NONE);
        add("granite", () -> Blocks.GRANITE, Tint.NONE);
        add("diorite", () -> Blocks.DIORITE, Tint.NONE);
        add("andesite", () -> Blocks.ANDESITE, Tint.NONE);
        add("tuff", () -> Blocks.TUFF, Tint.NONE);
        add("calcite", () -> Blocks.CALCITE, Tint.NONE);
        add("sandstone", () -> Blocks.SANDSTONE, Tint.NONE);
        add("red_sandstone", () -> Blocks.RED_SANDSTONE, Tint.NONE);
        add("terracotta", () -> Blocks.TERRACOTTA, Tint.NONE);
        add("netherrack", () -> Blocks.NETHERRACK, Tint.NONE);
        add("end_stone", () -> Blocks.END_STONE, Tint.NONE);
        add("oak_log", () -> Blocks.OAK_LOG, Tint.NONE);
        add("spruce_log", () -> Blocks.SPRUCE_LOG, Tint.NONE);
        add("birch_log", () -> Blocks.BIRCH_LOG, Tint.NONE);
        add("jungle_log", () -> Blocks.JUNGLE_LOG, Tint.NONE);
        add("acacia_log", () -> Blocks.ACACIA_LOG, Tint.NONE);
        add("dark_oak_log", () -> Blocks.DARK_OAK_LOG, Tint.NONE);
        add("mangrove_log", () -> Blocks.MANGROVE_LOG, Tint.NONE);
        add("cherry_log", () -> Blocks.CHERRY_LOG, Tint.NONE);
        add("pale_oak_log", () -> Blocks.PALE_OAK_LOG, Tint.NONE);
        add("oak_leaves", () -> Blocks.OAK_LEAVES, Tint.FOLIAGE);
        add("spruce_leaves", () -> Blocks.SPRUCE_LEAVES, Tint.SPRUCE);
        add("birch_leaves", () -> Blocks.BIRCH_LEAVES, Tint.BIRCH);
        add("jungle_leaves", () -> Blocks.JUNGLE_LEAVES, Tint.FOLIAGE);
        add("acacia_leaves", () -> Blocks.ACACIA_LEAVES, Tint.FOLIAGE);
        add("dark_oak_leaves", () -> Blocks.DARK_OAK_LEAVES, Tint.FOLIAGE);
        add("mangrove_leaves", () -> Blocks.MANGROVE_LEAVES, Tint.FOLIAGE);
        add("cherry_leaves", () -> Blocks.CHERRY_LEAVES, Tint.NONE);
        add("pale_oak_leaves", () -> Blocks.PALE_OAK_LEAVES, Tint.NONE);
        add("azalea_leaves", () -> Blocks.AZALEA_LEAVES, Tint.NONE);
        add("flowering_azalea_leaves", () -> Blocks.FLOWERING_AZALEA_LEAVES, Tint.NONE);
    }

    private static void add(String name, Supplier<Block> original, Tint tint) {
        String id = "decaying_" + name;
        DeferredHolder<Block, Block> holder = ModBlocks.BLOCKS.register(id, key -> new DecayingBlock(
                BlockBehaviour.Properties.ofFullCopy(original.get()).setId(ResourceKey.create(Registries.BLOCK, key))
                        // Some originals (logs) pick their map color from state properties this block doesn't have.
                        .mapColor(original.get().defaultMapColor()).noOcclusion(), original));
        ALL.add(new Entry(name, original, tint, holder));
    }

    /** The decaying version of a natural block, or null if the block is not natural. */
    public static BlockState decayingOf(BlockState state) {
        if (byOriginal == null) {
            Map<Block, Block> map = new IdentityHashMap<>();
            for (Entry e : ALL) map.put(e.original().get(), e.holder().get());
            byOriginal = map;
        }
        Block block = byOriginal.get(state.getBlock());
        return block == null ? null : block.defaultBlockState();
    }
}
